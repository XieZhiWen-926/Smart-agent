"""Repository 数据访问层：所有 SQL/ORM 查询都封装在这里。

【为什么要有这一层，而不是在路由里直接写 SQL？】
1. 复用：同一个查询（如"按手机号查客户"）可能在多个接口用到，写一遍到处调用；
2. 可维护：要改查询逻辑（加索引、改条件）只动一个文件，不用翻遍所有路由；
3. 可测试：单测时可以用假数据替换 repo，不用真的连数据库；
4. 职责清晰：路由管 HTTP，service 管业务规则，repo 管数据存取，各管一段。

在分层中的位置：services -> repositories(本层) -> models(ORM) -> MySQL。
本层只做"取数/存数"，不写业务校验（如手机号格式校验在 service 层）。
"""
